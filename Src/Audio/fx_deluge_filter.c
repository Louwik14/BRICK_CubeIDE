void fx_deluge_filter_reset(fx_deluge_filter_t *f) { if(f)memset(f->channel,0,sizeof(f->channel)); }
void fx_deluge_filter_configure(fx_deluge_filter_t *f,float morph,float cutoff,float resonance) {
 if(!f) return;
 cutoff=clampf_deluge(cutoff,10.0f,f->sample_rate*0.45f);
 resonance=clampf_deluge(resonance,0.0f,1.0f);
 f->frequency=clampf_deluge(deluge_cutoff_lookup(cutoff),0.001f,0.92f);
 const float q=1.0f-resonance; f->damping=q*q; f->input_gain=0.25f*(1.0f+q); morph=clampf_deluge(morph,0.0f,127.0f);
 if(morph==0.0f)f->morph_plan=FX_DELUGE_MORPH_LP; else if(morph<64.0f){const float t=morph*(1.0f/64.0f);f->morph_a=1.0f-t;f->morph_b=t;f->morph_plan=FX_DELUGE_MORPH_LP_BP;}
 else if(morph==64.0f)f->morph_plan=FX_DELUGE_MORPH_BP; else if(morph<127.0f){const float t=(morph-64.0f)*(1.0f/63.0f);f->morph_a=t;f->morph_b=1.0f-t;f->morph_plan=FX_DELUGE_MORPH_BP_HP;} else f->morph_plan=FX_DELUGE_MORPH_HP;
}
